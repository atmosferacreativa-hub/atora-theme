<p style="font-size: 16px; line-height: 1.75; color: var(--as-ink);"><span style="font-family: var(--as-font-serif); font-size: 56px; font-weight: 700; color: var(--as-blue); float: left; line-height: 0.8; padding-right: 8px; padding-top: 3px;">L</span>a pregunta fundamental que debe responder todo fotógrafo es: ¿quién soy como creador visual? No basta con dominar la técnica. La técnica es el instrumento. Tu visión es lo que importa.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"style":{"typography":{"fontFamily":"var(--as-font-serif)","fontSize":"32px","marginTop":"48px"}}} -->
<h2 style="font-family: var(--as-font-serif); font-size: 32px; margin-top: 48px;">Por qué el estilo importa</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>En un mundo saturado de imágenes, tu singularidad es tu mayor activo. Un estilo visual reconocible te diferencia, construye tu marca y atrae oportunidades profesionales.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>El estilo no es algo que se inventa de la noche a la mañana. Es el resultado de miles de decisiones conscientes: qué luz prefieres, cómo compones, qué paleta de color te representa, cómo editas.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2,"style":{"typography":{"fontFamily":"var(--as-font-serif)","fontSize":"32px","marginTop":"48px"}}} -->
<h2 style="font-family: var(--as-font-serif); font-size: 32px; margin-top: 48px;">Tres ejercicios para descubrir tu voz</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3,"style":{"typography":{"fontFamily":"var(--as-font-serif)","fontSize":"22px"}}} -->
<h3 style="font-family: var(--as-font-serif); font-size: 22px;">1. Analiza tus 100 mejores fotos</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>No las que crees que son técnicamente perfectas. Las que amas genuinamente. Mira patrones: ¿qué temas repiten? ¿Qué luz prefieres? ¿Hay colores que dominen? Documenta estos hallazgos.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"style":{"typography":{"fontFamily":"var(--as-font-serif)","fontSize":"22px"}}} -->
<h3 style="font-family: var(--as-font-serif); font-size: 22px;">2. Estudia referentes (pero no copies)</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Identifica fotógrafos cuyo trabajo te inspira. ¿Qué admirás? Entiende sus decisiones. Luego distanciate y pregunta: ¿cómo haría yo esto? Tu respuesta es más valiosa que la copia.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"style":{"typography":{"fontFamily":"var(--as-font-serif)","fontSize":"22px"}}} -->
<h3 style="font-family: var(--as-font-serif); font-size: 22px;">3. Experimenta con restricciones</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Limítate a un lente, una paleta de colores, un género. La restricción fuerza decisiones creativas. Descubrirás qué es esencial en tu visión.</p>
<!-- /wp:paragraph -->

<!-- Blockquote -->
<!-- wp:quote {"style":{"fontSize":"16px","fontStyle":"italic","borderLeftColor":"var(--as-blue)","borderLeftWidth":"4px","paddingLeft":"20px","marginTop":"48px"}} -->
<blockquote class="wp-block-quote" style="font-size: 16px; font-style: italic; border-left: 4px solid var(--as-blue); padding-left: 20px; margin-top: 48px;"><p>Tu estilo no es lo que ves. Es cómo decides mostrar lo que ves. Esa diferencia lo es todo.</p></blockquote>
<!-- /wp:quote -->

<!-- wp:heading {"level":2,"style":{"typography":{"fontFamily":"var(--as-font-serif)","fontSize":"32px","marginTop":"48px"}}} -->
<h2 style="font-family: var(--as-font-serif); font-size: 32px; margin-top: 48px;">Protege tu visión</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Una vez hayas identificado tu estilo, la tentación es comprometer. Porque alguien te pide que hagas "diferente", o porque comparás con lo que otros están haciendo. Resiste.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Tu consistencia visual es lo que construye reconocimiento. Clientes, galerías, medios y otras oportunidades acuden a fotógrafos con voz clara. No a fotógrafos que hacen de todo.</p>
